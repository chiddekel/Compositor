    }
    public func activate(ignoringOtherApps: Bool = true) {}
    /// The menu bar, as SwiftUI keeps it on the Mac: the app's `.commands`. The app module builds it on first use — the
    /// provider it installs, else its exported `compositor_main_menu` (so a process that never ran the shell, a test
    /// host, has one too). Nil in a process without the app.
    public var mainMenuProvider: (() -> NSMenu?)?
    private var mainMenuStorage: NSMenu?
    public var mainMenu: NSMenu? {
        get {
            if mainMenuStorage == nil { mainMenuStorage = mainMenuProvider?() ?? Self.exportedMainMenu() }
            return mainMenuStorage
        }
        set { mainMenuStorage = newValue }
    }
    private static func exportedMainMenu() -> NSMenu? {
        #if canImport(Glibc)
        typealias Maker = @convention(c) () -> UnsafeMutableRawPointer?
        guard let sym = dlopen(nil, RTLD_NOW).flatMap({ dlsym($0, "compositor_main_menu") }),
              let menu = unsafeBitCast(sym, to: Maker.self)() else { return nil }
        return Unmanaged<NSMenu>.fromOpaque(menu).takeRetainedValue()
        #else
        return nil
        #endif
    }
    /// A responder-chain action by name ("cut:", "undo:", ...); the host's text editing answers these (`actionHandler`).
    public var actionHandler: ((Selector) -> Bool)?
    /// When set, answers `selectAll:` the way a focused `LayerTableView` would (canvas select, not every layer).
    public var selectAllHandler: (() -> Bool)?
    @discardableResult public func sendAction(_ action: Selector, to target: Any?, from sender: Any?) -> Bool {
        // An explicit target gets the action, as AppKit's; with none, the key window's responder chain is asked first.
        if let target, NSPerform(target, action, with: sender) { return true }
        var responder: NSResponder? = keyWindow?.firstResponder
        while let current = responder {
            if let dispatching = current as? NSSelectorDispatching, dispatching.compatResponds(to: action) {
                return dispatching.compatPerform(action, with: sender)
            }
            responder = current.nextResponder
        }
        if actionHandler?(action) == true { return true }
        // Walk the key window's responder chain for selectAll: (field editor, LayerTableView, ...).
        if action.name == "selectAll:" || action.name == "selectAll" {
            var responder: NSResponder? = keyWindow?.firstResponder
            while let current = responder {
                if let table = current as? NSTableView {
                    table.selectAll(sender)
                    return true
                }
                responder = current.nextResponder
            }
            if selectAllHandler?() == true { return true }
        }
        return false
    }
    /// Hide / Hide Others / Show All: window-manager business on Linux (the host may set these).
    public var hideHandler: (() -> Void)?
    public func hide(_ sender: Any?) { hideHandler?() }
    public func hideOtherApplications(_ sender: Any?) {}
    public func unhideAllApplications(_ sender: Any?) {}
}

