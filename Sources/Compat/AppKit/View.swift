/// Objective-C selectors are just names here (target/action wiring is the Qt shell's job).
public struct Selector: Hashable, ExpressibleByStringLiteral, Sendable {
    public let name: String
    public init(_ name: String) { self.name = name }
    public init(stringLiteral value: String) { name = value }
}

public func NSSelectorFromString(_ name: String) -> Selector { Selector(name) }
public func NSStringFromSelector(_ selector: Selector) -> String { selector.name }

/// Target-action without an Objective-C runtime. On the Mac a `#selector` names an `@objc` method the runtime finds by
/// name; here a class answers the names itself. Sources generated by `scripts/objc_selectors.py` conform with a `switch`
/// over exactly the methods their `#selector`s named, so nothing else is reachable by name.
@MainActor public protocol NSSelectorDispatching: AnyObject {
    /// Runs the method `selector` names with `argument` (the sender, or nothing); false when this class has no such method.
    func compatPerform(_ selector: Selector, with argument: Any?) -> Bool
    func compatResponds(to selector: Selector) -> Bool
}

/// `target.perform(selector)` for any object: only `NSSelectorDispatching` targets answer.
@MainActor @discardableResult
public func NSPerform(_ target: Any?, _ selector: Selector, with argument: Any? = nil) -> Bool {
    (target as? NSSelectorDispatching)?.compatPerform(selector, with: argument) ?? false
}

