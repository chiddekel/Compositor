    open var layer: CALayer? { wantsLayer ? backingLayer : nil }
    private lazy var backingLayer = CALayer()
    public var clipsToBounds = false
    /// The part of the view waiting to be redrawn, in its own coordinates — what AppKit accumulates from
    /// `setNeedsDisplay(_:)` until the next display. A host that draws the view (the Qt canvas) repaints just this.
    public private(set) var invalidRect: CGRect?
    public var needsDisplay: Bool {
        get { invalidRect != nil }
        set { invalidRect = newValue ? bounds : nil }
    }
    public var needsLayout = false
    public private(set) var trackingAreas: [NSTrackingArea] = []
    public var backingScaleFactor: CGFloat { window?.backingScaleFactor ?? 1 }
    open var isFlipped: Bool { false }
    open var isOpaque: Bool { false }
    open func acceptsFirstMouse(for event: NSEvent?) -> Bool { false }
    open var visibleRect: CGRect { bounds }

    public init(frame: CGRect) { self.frame = frame; super.init() }
    public override convenience init() { self.init(frame: .zero) }
    public required init?(coder: NSCoder) { fatalError("init(coder:) is unavailable") }

    open func addSubview(_ view: NSView) {
        view.removeFromSuperview()
        view.viewWillMove(toSuperview: self)
        if view.window !== window { view.viewWillMove(toWindow: window) }
        view.superview = self; subviews.append(view)
        needsLayout = true
        view.windowDidChange()
    }
    open func addSubview(_ view: NSView, positioned place: NSWindow.OrderingMode, relativeTo other: NSView?) {
        view.removeFromSuperview()
        view.superview = self
        if let other, let index = subviews.firstIndex(where: { $0 === other }) {
            subviews.insert(view, at: place == .below ? index : index + 1)
        } else if place == .below {
            subviews.insert(view, at: 0)
        } else {
            subviews.append(view)
        }
        view.windowDidChange()
    }
    /// Whether this view is `view` or lies inside it.
    public func isDescendant(of view: NSView) -> Bool {
        var current: NSView? = self
        while let candidate = current {
            if candidate === view { return true }
            current = candidate.superview
        }
        return false
    }
    open func removeFromSuperview() {
        guard let superview else { return }
        viewWillMove(toSuperview: nil)
        if window != nil { viewWillMove(toWindow: nil) }
        // As AppKit: constraints between this view and the hierarchy it leaves go with it.
        for constraint in NSLayoutConstraint.active
        where [constraint.firstAttribute.item, constraint.secondAttribute?.item].contains(where: { $0 === self }) {
            constraint.isActive = false
        }
        superview.subviews.removeAll { $0 === self }
        self.superview = nil
        windowDidChange()
    }
    /// Tells this view and everything below it that the window it belongs to may have changed (AppKit sends
    /// `viewDidMoveToWindow` down the whole subtree when a hierarchy is attached to or detached from a window).
    func windowDidChange() {
        notifiedWindow = window
        viewDidMoveToWindow()
        for child in subviews where child.notifiedWindow !== window { child.windowDidChange() }
    }
    private weak var notifiedWindow: NSWindow?
    open func setFrameOrigin(_ origin: CGPoint) { frame.origin = origin }
    open func setFrameSize(_ size: CGSize) { frame.size = size }
    open func setNeedsDisplay(_ rect: CGRect) {
        guard !rect.isEmpty else { return }
        invalidRect = invalidRect.map { $0.union(rect) } ?? rect
    }
    open func setNeedsDisplay() { needsDisplay = true }
    /// A bitmap sized for this view's rect at the window's backing scale, to draw into with `cacheDisplay`.
    open func bitmapImageRepForCachingDisplay(in rect: CGRect) -> NSBitmapImageRep? {
        let w = max(1, Int((rect.width * backingScaleFactor).rounded(.up))), h = max(1, Int((rect.height * backingScaleFactor).rounded(.up)))
        // A real Core Graphics bitmap context: origin bottom-left, so images draw upright in a non-flipped view.
        guard let ctx = CGContext(data: nil, width: w, height: h, bitsPerComponent: 8, bytesPerRow: w * 4,
                                  space: CGColorSpace(name: CGColorSpace.sRGB)!,
                                  bitmapInfo: CGImageAlphaInfo.premultipliedLast.rawValue) else { return nil }
        return NSBitmapImageRep(context: ctx)
    }
    /// Renders the view into `rep` by running its `draw(_:)` with the rep's context current, in the view's own
    /// coordinates: y-up for regular views, y-down for flipped ones (the context itself is top-left based).
    open func cacheDisplay(in rect: CGRect, to rep: NSBitmapImageRep) {
        guard let ctx = rep.context else { return }
        NSGraphicsContext.saveGraphicsState()
        defer { NSGraphicsContext.restoreGraphicsState() }
        NSGraphicsContext.current = NSGraphicsContext(cgContext: ctx, flipped: isFlipped)
        ctx.saveGState()
        ctx.scaleBy(x: backingScaleFactor, y: backingScaleFactor)
        // The bitmap context is y-up like Core Graphics's, so a flipped view flips it back to its own y-down space.
        if isFlipped { ctx.translateBy(x: 0, y: rect.height); ctx.scaleBy(x: 1, y: -1) }
        ctx.translateBy(x: -rect.minX, y: -rect.minY)
        viewWillDraw()
        draw(rect)
        for child in subviews where !child.isHidden {
            ctx.saveGState()
            ctx.translateBy(x: child.frame.minX, y: child.frame.minY)
            child.draw(child.bounds)
            ctx.restoreGState()
        }
        ctx.restoreGState()
    }
    open func displayIfNeeded() { if needsDisplay { viewWillDraw(); needsDisplay = false } }
    private var hasDisplayed = false
    func displayTreeIfNeeded(force: Bool = false) {
        guard !isHidden else { return }
        layoutSubtreeIfNeeded()
        if force || needsDisplay || !hasDisplayed {
            let width = min(max(Int(bounds.width.rounded(.up)), 1), 4096), height = min(max(Int(bounds.height.rounded(.up)), 1), 4096)
            if let ctx = CGContext(data: nil, width: width, height: height, bitsPerComponent: 8, bytesPerRow: width * 4,
                                   space: CGColorSpace(name: CGColorSpace.sRGB)!,
                                   bitmapInfo: CGImageAlphaInfo.premultipliedLast.rawValue) {
                NSGraphicsContext.saveGraphicsState()
                NSGraphicsContext.current = NSGraphicsContext(cgContext: ctx, flipped: isFlipped)
                if isFlipped { ctx.translateBy(x: 0, y: CGFloat(height)); ctx.scaleBy(x: 1, y: -1) }
                ctx.translateBy(x: -bounds.minX, y: -bounds.minY)
                viewWillDraw()
                draw(bounds)
                NSGraphicsContext.restoreGraphicsState()
            }
            hasDisplayed = true
            needsDisplay = false
        }
        for child in subviews { child.displayTreeIfNeeded(force: force) }
    }
    /// As AppKit's: this view's constraints place its subviews and guides, then `layout()` runs; then the same for
    /// each subview that needs it.
    open func layoutSubtreeIfNeeded() {
        if needsLayout {
            solveConstraints()
            layout()
            needsLayout = false
        }
        for child in subviews { child.layoutSubtreeIfNeeded() }
    }
    open func layout() {}
    /// No cached intrinsic size is kept (layout asks `fittingSize` directly), so there is nothing to discard.
    open func invalidateIntrinsicContentSize() {}
    /// The size the view's content wants, per axis; `noIntrinsicMetric` where it has none (the default), as in AppKit.
    /// A hosting view sizes a `.fixedSize()` representable from it.
    open var intrinsicContentSize: NSSize { NSSize(width: NSView.noIntrinsicMetric, height: NSView.noIntrinsicMetric) }
    /// The size that fits the content: the intrinsic size where the view has one, its current size otherwise.
    open var fittingSize: NSSize {
        let intrinsic = intrinsicContentSize
        return NSSize(width: intrinsic.width >= 0 ? intrinsic.width : frame.width,
                      height: intrinsic.height >= 0 ? intrinsic.height : frame.height)
    }
    public static let noIntrinsicMetric: CGFloat = -1
    open func viewWillDraw() {}
    open func viewDidMoveToWindow() {}
    open func viewDidChangeBackingProperties() {}
    open func updateTrackingAreas() {}
    open func addTrackingArea(_ area: NSTrackingArea) { trackingAreas.append(area) }
    open func removeTrackingArea(_ area: NSTrackingArea) { trackingAreas.removeAll { $0 === area } }
    /// Cursor rects as `resetCursorRects` adds them (AppKit's cursor-rect machinery, asked by the host on hover).
    public private(set) var cursorRects: [(rect: CGRect, cursor: NSCursor)] = []
