    open func reloadData() {
        for (_, view) in rowViews {
            view.removeFromSuperview()
            if let identifier = view.identifier { recycledViews[identifier, default: []].append(view) }
        }
        rowViews = [:]
        rowOrigins = nil
        needsDisplay = true
        needsLayout = true
    }
