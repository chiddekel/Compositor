// host_run.cpp — the Qt host entry called by the Swift composition root.
//
// The Linux port's composition root is inverted: a Swift `@main`
// (Sources/CompositorHostBootstrap/hostMain.swift) bootstraps the Swift runtime
// + Foundation (which a C++ main cannot on the Freedesktop Swift 6.3 SDK), then
// calls this `compositor_host_run` C entry to run the Qt Widgets shell. The Qt
// host in turn calls back into the Swift core through the `compositor_session_*`
// C ABI (ENG-1). The standalone CMake `compositor` target keeps its own `main`
// (host/main.cpp) for the C++-only build path.
//
// This entry creates the real `MainWindow` (host/MainWindow.h, Q_OBJECT). Its
// moc output (host/moc_MainWindow.cpp) is generated by `moc` and committed so
// SwiftPM can build it without AUTOMOC. The Flatpak build rebuilds the same
// window via CMake/AUTOMOC; this SwiftPM path proves the moc'd-Qt -> Swift-@main
// link. The headless proof processes pending paint events without entering the
// blocking event loop; the Flatpak app calls app.exec() here.

#include <QApplication>
#include <QCoreApplication>
#include <QProcessEnvironment>
#include <QTemporaryDir>
#include <QFile>
#include <QDir>

#include "compositor_host_run.h"
#include "EditorDialogs.h"
#include "ColorPickerDialog.h"
#include <cmath>
#include <vector>
#include <QJsonObject>
#include "SessionWindow.h"

#if defined(COMPOSITOR_SKIA_BRIDGE)
#include "SkiaBridge.h"
#endif

extern "C" int compositor_host_run(int argc, char **argv) {
    QApplication app(argc, argv);
    app.setApplicationName("Compositor");
    app.setOrganizationName("Compositor");
    app.setDesktopFileName("com.wonderassembly.Compositor");
#if defined(COMPOSITOR_SKIA_BRIDGE)
    // Plan §6 startup: try Vulkan, fall back to Raster. The renderer backs
    // the Swift CGContextCompat shim; on any failure the Swift
    // DocumentRenderer remains the ultimate fallback.
    CompRendererKind kind = COMP_RENDERER_RASTER;
    CompRenderer *renderer = compositor_renderer_create(0, &kind);
    if (renderer) compositor_renderer_activate(renderer);
#endif
    // SessionWindow (moc'd Q_OBJECT) drives the Swift core via compositor_session_*
    // and paints the composited RGBA — the architecture the Flatpak build ships.
    // The richer MainWindow (C-kernels Qt shell) is the C++-only build path's window.
    SessionWindow window;
    window.show();
    // CI and Swift smoke runs use offscreen Qt. Real desktop launches keep the
    // event loop alive; offscreen runs only need one paint pass.
    if (!qEnvironmentVariable("COMPOSITOR_GRAB_PATH").isEmpty()) {
        if (qEnvironmentVariable("COMPOSITOR_GRAB_TOOL") == "move") window.setTool(SessionWindow::Tool::Move);
        for (int i = 0; i < 10; ++i) {
            QCoreApplication::processEvents();
        }
        window.grab().save(qEnvironmentVariable("COMPOSITOR_GRAB_PATH"));
        // COMPOSITOR_GRAB_DIALOG=<Adjust kind | ColorPicker> also captures that dialog as <path>.dialog.png.
        const QString dialogKind = qEnvironmentVariable("COMPOSITOR_GRAB_DIALOG");
        if (!dialogKind.isEmpty()) {
            QDialog *dialog = nullptr;
            if (dialogKind == "ColorPicker") {
                dialog = new ColorPickerDialog(QColor(0xFA, 0x75, 0x27), QStringLiteral("Color Picker (Foreground Color)"), &window);
            } else {
                dialog = new AdjustDialog(dialogKind, [](const QJsonObject &) { return true; }, &window, [](int) {
                    std::vector<double> bins(256);
                    for (int i = 0; i < 256; ++i) bins[i] = 40.0 * std::exp(-std::pow((i - 60) / 40.0, 2)) + 15.0 * std::exp(-std::pow((i - 170) / 60.0, 2)) + (i < 6 ? 60 : 1);
                    return bins;
                });
            }
            dialog->show();
            for (int i = 0; i < 10; ++i) QCoreApplication::processEvents();
            dialog->grab().save(qEnvironmentVariable("COMPOSITOR_GRAB_PATH") + ".dialog.png");
        }
        return 0;
    }
    if (qEnvironmentVariable("QT_QPA_PLATFORM") == "offscreen") {
        QCoreApplication::processEvents();
        return 0;
    }
    return app.exec();
}

extern "C" int compositor_host_io_smoke(int argc, char **argv) {
    QApplication app(argc, argv);
    QTemporaryDir temporary;
    if (!temporary.isValid()) return 1;
    SessionWindow window;
    const QString root = temporary.path();
    if (!window.exportPNG(root + "/export.png") || !QFile::exists(root + "/export.png")) return 2;
    if (!window.exportJPEG(root + "/export.jpg", 90) || !QFile::exists(root + "/export.jpg")) return 3;
    if (!window.saveProject(root + "/project")) return 4;
    if (!QFile::exists(root + "/project/manifest.json") ||
        QDir(root + "/project/images").entryList(QDir::Files).isEmpty()) return 5;
    if (!window.loadProject(root + "/project")) return 6;
    return 0;
}
