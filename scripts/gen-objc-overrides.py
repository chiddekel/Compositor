#!/usr/bin/env python3
"""Generate Linux overrides of tip AppKit files that need the Objective-C runtime.

Linux Swift has no Objective-C interop: `#selector`, `@objc` and method swizzling don't compile. Each output here is
tip's own file, rewritten mechanically by scripts/objc_selectors.py (selectors by name, dispatched through compat
AppKit's `NSSelectorDispatching`), plus the smallest Linux replacement where tip swizzles. A tip change regenerates;
`--check` fails when an output is stale.

  scripts/gen-objc-overrides.py [--check]
"""
import argparse
from pathlib import Path
import shutil
import subprocess
import sys
import tempfile

sys.path.insert(0, str(Path(__file__).resolve().parent))
import objc_selectors  # noqa: E402

root = Path(__file__).resolve().parents[1]


def header(tip, note):
    return (f'// GENERATED by scripts/gen-objc-overrides.py from {tip}; do not edit.\n'
            + ''.join(f'// {line}\n' if line else '//\n' for line in note.split('\n')))


def slider_snap():
    tip = 'Compositor/UI/SliderSnap.swift'
    source = (root / tip).read_text()
    # Tip swizzles NSSliderCell.startTracking(at:in:) through the Objective-C runtime. Compat AppKit's cell runs
    # `NSSliderCell.startTrackingHook` at the same moment instead; the snap itself (the extension below) is tip's.
    swizzle_start = source.index('    private static let installed: Void = {')
    swizzle_end = source.index('    }()\n', swizzle_start) + len('    }()\n')
    source = source[:swizzle_start] + (
        '    private static let installed: Void = {\n'
        '        NSSliderCell.startTrackingHook = { cell, point, view in cell.snapValue(to: point, in: view) }\n'
        '    }()\n') + source[swizzle_end:]
    source = source.replace('import ObjectiveC\n', '')
    if 'class_getInstanceMethod' in source or 'method_setImplementation' in source:
        raise SystemExit(f'{tip}: swizzle not fully replaced')
    return header(tip, 'Only the swizzle in `installed` differs: compat NSSliderCell calls `startTrackingHook` where tip\n'
                       'replaced startTracking(at:in:) through the Objective-C runtime.') + source


def command_palette_view():
    tip = 'Compositor/UI/CommandPaletteView.swift'
    source = (root / tip).read_text()
    # Tip shows the palette in an NSPanel; on Linux the Qt shell shows its CommandPaletteDialog over the editor, from
    # the same menus (ShellProjects queues "commandPalette").
    marker = '        if isOpen { close(); return }\n'
    start = source.index(marker)
    end = source.index('        panel.makeKeyAndOrderFront(nil)\n', start) + len('        panel.makeKeyAndOrderFront(nil)\n')
    source = source[:start] + (
        '        _ = (session, window, menu)\n'
        '        ShellProjects.enqueue("commandPalette")\n') + source[end:]
    return header(tip, 'Only `toggle` differs: the Qt shell presents CommandPaletteDialog (queued as "commandPalette") where\n'
                       'tip builds an NSPanel. Search, ranking, the model and `skipped` are tip\'s (UI/CommandPalette.swift).'
                  ) + objc_selectors.port(source)


def window_delegate_methods():
    """The compat `NSWindowDelegate` requirements: [(name, parameter list, return clause)]."""
    text = (root / 'Sources/Compat/AppKit/Panel.swift').read_text()
    body = text[text.index('public protocol NSWindowDelegate'):]
    body = body[:body.index('}')]
    import re
    return re.findall(r'func (\w+)\(([^)]*)\)\s*(->\s*\w+)?', body)


def project_window_bridge():
    tip = 'Compositor/UI/ProjectWindowBridge.swift'
    source = (root / tip).read_text()
    # Tip forwards every NSWindowDelegate callback it doesn't implement to the delegate it replaced, through the
    # Objective-C runtime (responds(to:) / forwardingTarget(for:)). Without a runtime the same forwarding is written
    # out: one forwarder per compat NSWindowDelegate callback the proxy doesn't declare.
    owner = 'private final class ProjectWindowDelegate: NSObject, NSWindowDelegate {'
    start = source.index(owner)
    end = source.index('\n}\n', start)
    declared = set(objc_selectors.re.findall(r'func (\w+)\(', source[start:end]))
    for header_line in ('    override func responds(to selector: Selector!) -> Bool {',
                        '    override func forwardingTarget(for selector: Selector!) -> Any? {'):
        source = objc_selectors.drop_declaration(source, header_line)
    forwarders = []
    for name, params, returns in window_delegate_methods():
        if name in declared:
            continue
        if returns:
            raise SystemExit(f'{tip}: NSWindowDelegate.{name} returns a value; forwarding it needs a default')
        label, _, rest = params.partition(' ')
        argument = rest.split(':')[0].strip()
        forwarders.append(f'    func {name}({params}) {{ previous?.{name}({argument}) }}\n')
    end = source.index('\n}\n', source.index(owner))
    source = source[:end + 1] + '    // Forwarded to the delegate this one replaced (tip: forwardingTarget(for:)).\n' + ''.join(forwarders) + source[end + 1:]
    return header(tip, 'Only the forwarding differs: tip forwards unhandled NSWindowDelegate callbacks to `previous` through\n'
                       'the Objective-C runtime; here each compat NSWindowDelegate callback the proxy doesn\'t declare is\n'
                       'forwarded explicitly.') + objc_selectors.port(source)


def patched(tip, patch):
    """Tip's file with a Linux patch (linux/patches) applied, exactly (no fuzz)."""
    with tempfile.TemporaryDirectory() as directory:
        target = Path(directory) / tip
        target.parent.mkdir(parents=True)
        shutil.copy(root / tip, target)
        subprocess.run(['patch', '--batch', '--fuzz=0', '--quiet', '-p1', '-d', directory, '-i', str(root / patch)],
                       check=True, stdout=subprocess.DEVNULL)
        return target.read_text()


def keyboard_shortcuts():
    tip = 'Compositor/UI/KeyboardShortcuts.swift'
    patch = 'linux/patches/keyboard-shortcuts-linux.patch'
    return header(tip, f'Tip\'s file with {patch} (Linux key names and messages, the sheet kept while open, defaults\n'
                       'written at once), through scripts/objc_selectors.py. The recorder is tip\'s NSButton; the Qt shell\n'
                       'draws it as a Button and hands it the next key while it is first responder (compat NativeLowering).'
                  ) + objc_selectors.port(patched(tip, patch))


def plain(tip, note, rewrites=()):
    """Tip's file through scripts/objc_selectors.py, plus exact `(old, new)` rewrites each found exactly once."""
    def make():
        source = (root / tip).read_text()
        for old, new in rewrites:
            if source.count(old) != 1:
                raise SystemExit(f'{tip}: {old!r} found {source.count(old)} times')
            source = source.replace(old, new)
        return header(tip, note) + objc_selectors.port(source)
    return make


def latin_keys():
    tip = 'Compositor/UI/LatinKeys.swift'
    source = (root / tip).read_text().replace('import Carbon.HIToolbox\n', '')
    marker = '    static func character(for keyCode: UInt16, shift: Bool) -> String? {'
    start = source.index(marker)
    # This is the final method; keep the entire event-normalization algorithm unchanged.
    if not source.endswith('    }\n}\n'):
        raise SystemExit(f'{tip}: review the keyboard-layout adapter after the upstream change')
    source = source[:start] + marker + '\n        NSKeyboardLayout.latinCharacter(for: keyCode, shift: shift)\n    }\n}\n'
    return header(tip, 'Only Carbon layout lookup is replaced by the host-provided AppKit keyboard-layout contract.\n'
                       'Event normalization and the ASCII/non-ASCII guards remain upstream code.') + source


