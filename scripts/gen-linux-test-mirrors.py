#!/usr/bin/env python3
"""Linux mirrors of upstream tests requiring platform syntax or type-name adaptation.

Linux Swift has no Objective-C interop, so a test file with `#selector(...)` doesn't compile however complete compat
AppKit is. Its mirror in Tests/LinuxOverrideTests is the upstream file with each `#selector(T.m)` written as the
`Selector("m:")` it evaluates to on the Mac (named from the tip declaration, by scripts/objc_selectors.py) and nothing
else changed; the upstream file stays excluded and untouched. `--check` fails when a mirror is stale or differs from
upstream anywhere but those expressions.

  scripts/gen-linux-test-mirrors.py [--check]
"""
import argparse
from pathlib import Path
import re
import sys

sys.path.insert(0, str(Path(__file__).resolve().parent))
import objc_selectors  # noqa: E402

root = Path(__file__).resolve().parents[1]

# Mirror name → (upstream test, tip sources declaring the methods its selectors name).
MIRRORS = {
    'LayerTests': ('CompositorTests/LayerTests.swift', ['Compositor/UI/NativeLayerList.swift']),
}
DEFAULTS_MIRRORS = {'KeyboardShortcutTests': 'CompositorTests/KeyboardShortcutTests.swift'}


def mirror(test, sources):
    decls = [d for source in sources for d in objc_selectors.declarations((root / source).read_text())]
    text = (root / test).read_text()
    out = objc_selectors.rewrite_selectors(text, decls)
    # Nothing but the selector expressions may differ.
    pattern = re.compile(objc_selectors._SELECTOR.pattern)
    if pattern.sub('#', text) != re.sub(r'Selector\("[\w:]+"\)', '#', out):
        raise SystemExit(f'{test}: mirror differs from upstream beyond #selector expressions')
    return (f'// GENERATED by scripts/gen-linux-test-mirrors.py from {test}; do not edit.\n'
            '// Each #selector(T.m) is the Selector("m:") it evaluates to on the Mac; nothing else differs.\n') + out


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    stale = []
    for name, (test, sources) in MIRRORS.items():
        text = mirror(test, sources)
        target = root / 'Tests/LinuxOverrideTests' / f'{name}.swift'
        if args.check:
            if not target.exists() or target.read_text() != text:
                stale.append(str(target.relative_to(root)))
        else:
            target.write_text(text)
    for name, test in DEFAULTS_MIRRORS.items():
        # @testable Compositor exposes its SQLite UserDefaults alias alongside Foundation.UserDefaults.
        # Name that same implementation explicitly; every upstream test and assertion remains unchanged.
        original = (root / test).read_text()
        adapted = re.sub(r'\bUserDefaults\b', 'SQLiteUserDefaults', original)
        if re.sub(r'\bSQLiteUserDefaults\b', 'UserDefaults', adapted) != original:
            raise SystemExit(f'{test}: ambiguous pre-existing SQLiteUserDefaults name')
        text = (f'// GENERATED by scripts/gen-linux-test-mirrors.py from {test}; do not edit.\n'
                '// UserDefaults names the same SQLiteUserDefaults implementation used by Compositor on Linux.\n') + adapted
        target = root / 'Tests/LinuxOverrideTests' / f'{name}.swift'
        if args.check:
            if not target.exists() or target.read_text() != text:
                stale.append(str(target.relative_to(root)))
        else:
            target.write_text(text)
    if stale:
        print('stale (run scripts/gen-linux-test-mirrors.py):', *stale, sep='\n  ')
        return 1
    return 0


if __name__ == '__main__':
    sys.exit(main())
