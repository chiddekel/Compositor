#!/usr/bin/env python3
"""Generate checked RGBA entry points from the protected AdjustPixels header."""
import argparse
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[1]
header = (ROOT / 'Compositor/Rendering/AdjustPixels.h').read_text()
header = re.sub(r'/\*.*?\*/|//[^\n]*', '', header, flags=re.S)
entries = []
for name, parameters in re.findall(r'\bvoid\s+(\w+)\s*\(([^;{}]*)\)\s*;', header):
    parameters = ' '.join(parameters.split())
    names = [re.search(r'(\w+)\s*(?:\[[^]]*\])?$', parameter.strip()).group(1)
             for parameter in parameters.split(',')]
    if 'stride' in names:
        assert 'width' in names, name
        entries.append((name, parameters, names))
assert entries, 'No canonical RGBA entries found'
lines = ['// GENERATED by scripts/gen-checked-adjust-kernel.py from the protected AdjustPixels.h.',
         '// The upstream kernel compiles unchanged; checked entries reject padded RGBA strides.',
         '#include "CompositorKernelChecks.h"']
lines += [f'#define {name} {name}__unchecked' for name, _, _ in entries]
lines += ['#include "../../Compositor/Rendering/AdjustPixels.c"']
lines += [f'#undef {name}' for name, _, _ in entries]
for name, parameters, names in entries:
    # These upstream 1.5.3 APIs honor stride and explicitly test padded RGBA rows.
    contract = 'ROW' if name in {'adjust_camera_raw', 'camera_raw_repair_lookup'} else 'CANONICAL'
    lines += ['', f'void {name}({parameters}) {{',
              f'    COMPOSITOR_REQUIRE_{contract}("{name}", stride, width, 4);']
    if 'blurredStride' in names:
        lines += [f'    COMPOSITOR_REQUIRE_CANONICAL("{name}", blurredStride, width, 4);']
    lines += [f'    {name}__unchecked({", ".join(names)});', '}']
content = '\n'.join(lines) + '\n'
output = ROOT / 'linux/kernels/CheckedAdjustPixels.c'
parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument('--check', action='store_true')
args = parser.parse_args()
if args.check:
    assert output.read_text() == content, f'Stale checked kernel: {output}'
elif output.read_text() != content:
    output.write_text(content)
