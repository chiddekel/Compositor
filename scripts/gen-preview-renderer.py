#!/usr/bin/env python3
"""Expose preview scale and spatial sampling origin without editing macOS source."""
import argparse
from pathlib import Path

root = Path(__file__).resolve().parents[1]
source = (root / "Compositor/IO/ImageExporter.swift").read_text()
start = source.index("    func render(_ snapshot: ProjectSnapshot")
# Tip 1.4 inserts Quick Look helpers between render and pngData; only the render body is mirrored.
for marker in ("    func quickLookImages(", "    func pngData("):
    if marker in source[start:]:
        end = source.index(marker, start)
        break
else:
    raise SystemExit("Upstream ImageExporter layout changed (no quickLookImages/pngData after render)")
method = source[start:end]
# Tip 1.4.10+ adds `sixteenBit:` / `hdr:` after the snapshot; the preview keeps them, with the scale first.
signature = "func render(_ snapshot: ProjectSnapshot"
anchor = "            live.adjustment = { records[$0]?.adjustment }"
assert method.count(signature) == 1 and method.count(anchor) == 1, "Upstream renderer changed"
# Nonisolated: the exporter actor holds no state of its own (its caches lock themselves), and a preview render must
# not need a free thread of the Swift concurrency pool. The shell's main-thread renders used to hand it to the actor
# and block on a semaphore; with every pool thread waiting for the main queue, that never came back (GAP-TEST-01).
method = method.replace(signature, "nonisolated func renderPreview(_ snapshot: ProjectSnapshot, scale: CGFloat, samplingOrigin: CGPoint = .zero", 1)
method = method.replace(anchor, "            live.adjustmentScale = scale\n" + anchor)
pool = "        return try autoreleasepool {"
assert method.count(pool) == 1, "Upstream preview pool changed"
method = method.replace(pool, "        return try CISpatialSampling.$origin.withValue(samplingOrigin) {\n            try autoreleasepool {", 1)
closing = "        }\n    }\n"
assert closing in method, "Upstream render ending changed"
before, after = method.rsplit(closing, 1)
method = before + "            }\n        }\n    }\n" + after
output = (
    "// GENERATED by scripts/gen-preview-renderer.py from Compositor/IO/ImageExporter.swift.\n"
    "// The entry point, preview scale and scoped sampling origin differ from upstream.\n"
    "import Foundation\nimport CoreGraphics\nimport CoreImage\n\nextension ImageExporter {\n" + method + "}\n"
)
target = root / "Sources/LinuxBridge/PreviewRenderer.swift"
parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument("--check", action="store_true")
args = parser.parse_args()
if args.check:
    if not target.exists() or target.read_text() != output:
        raise SystemExit("Linux preview renderer is stale; run scripts/gen-preview-renderer.py")
else:
    target.write_text(output)
