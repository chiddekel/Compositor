#!/usr/bin/env bash
# Writes host/AppVersion.h from the Xcode project's MARKETING_VERSION / CURRENT_PROJECT_VERSION, so the Linux About
# panel shows the version the Mac app does. Run after every upstream merge; --check fails when the header is stale.
set -euo pipefail
ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
PBX="$ROOT/Compositor.xcodeproj/project.pbxproj"
VERSION="$(sed -n 's/.*MARKETING_VERSION = \([^;]*\);/\1/p' "$PBX" | head -1)"
BUILD="$(sed -n 's/.*CURRENT_PROJECT_VERSION = \([^;]*\);/\1/p' "$PBX" | head -1)"
HEADER="// GENERATED by scripts/sync-version.sh from Compositor.xcodeproj — do not edit.
#pragma once
#define COMPOSITOR_VERSION \"$VERSION\"
#define COMPOSITOR_BUILD \"$BUILD\""
if [[ "${1:-}" == "--check" ]]; then
  if [[ "$(cat "$ROOT/host/AppVersion.h")" != "$HEADER" ]]; then
    echo "host/AppVersion.h is stale (Xcode project: $VERSION build $BUILD); run scripts/sync-version.sh" >&2
    exit 1
  fi
  exit 0
fi
printf '%s\n' "$HEADER" > "$ROOT/host/AppVersion.h"
