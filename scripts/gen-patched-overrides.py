#!/usr/bin/env python3
"""Generate the Linux overrides that are tip's file with a small Linux patch (linux/patches/*-linux.patch).

Each output is the tip file with its patch applied exactly (no fuzz), so an upstream change to the file comes through
by regenerating; a change the patch no longer fits stops the generator, which is the point to look at the patch again.
`--check` fails when an output is stale.

  scripts/gen-patched-overrides.py [--check]
"""
import argparse
from pathlib import Path
import shutil
import subprocess
import sys
import tempfile

root = Path(__file__).resolve().parents[1]

OUTPUTS = {
    'Sources/Overrides/ProjectWorkspace.swift': (
        'Compositor/Document/ProjectWorkspace.swift', 'linux/patches/project-workspace-linux.patch',
        'Register newly created artboard sessions with the importing native window; upstream tab/import algorithms are unchanged.'),
    'Sources/Overrides/ContentView.swift': (
        'Compositor/ContentView.swift', 'linux/patches/content-view-linux.patch',
        'The Qt shell renders toolHeaders, toolRail and statusBar on their own (internal here), shows Color Range in its\n'
        'own panel, and `body` is split in two so the compat type checker finishes; a stand-in app delegate (tip\'s is\n'
        'excluded: Qt owns the app\'s lifecycle).'),
    'Sources/Overrides/IndicatorlessScrollView.swift': (
        'Compositor/UI/IndicatorlessScrollView.swift', 'linux/patches/indicatorless-scroll-view-linux.patch',
        'Only an explicit nonisolated deinit added: Swift 6.3.3 crashes emitting the generic Container\'s main-actor deinit.'),
    'Sources/Overrides/TransformOverlay.swift': (
        'Compositor/Rendering/TransformOverlay.swift', 'linux/patches/transform-overlay-linux.patch',
        'Transform handles use 16-point mouse or 28-point touch hit areas, capped to preserve a draggable interior on small objects. Drawn sizes are unchanged.'),
}


def patched(tip, patch):
    with tempfile.TemporaryDirectory() as directory:
        target = Path(directory) / tip
        target.parent.mkdir(parents=True)
        shutil.copy(root / tip, target)
        subprocess.run(['patch', '--batch', '--fuzz=0', '--quiet', '-p1', '-d', directory, '-i', str(root / patch)],
                       check=True, stdout=subprocess.DEVNULL)
        return target.read_text()


def generate(tip, patch, note):
    header = f'// GENERATED by scripts/gen-patched-overrides.py from {tip} and {patch}; do not edit.\n'
    header += ''.join(f'// {line}\n' for line in note.split('\n'))
    return header + patched(tip, patch)


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    stale = []
    # History and RawDevelopSheet now compile unchanged from upstream; reject old copies that would duplicate types.
    for retired_rel in ("Sources/Overrides/DocumentHistory.swift", "Sources/Overrides/RawDevelopSheet.swift"):
        retired = root / retired_rel
        if retired.exists():
            if args.check:
                stale.append(str(retired.relative_to(root)))
            else:
                retired.unlink()
    for path, (tip, patch, note) in OUTPUTS.items():
        text = generate(tip, patch, note)
        target = root / path
        if args.check:
            if not target.exists() or target.read_text() != text:
                stale.append(path)
        else:
            target.write_text(text)
    if stale:
        print('stale (run scripts/gen-patched-overrides.py):', *stale, sep='\n  ')
        return 1
    return 0


if __name__ == '__main__':
    sys.exit(main())
