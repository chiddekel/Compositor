#!/usr/bin/env python3
"""Generates host/LucideIcons.h: the Lucide SVGs (third_party/lucide/icons) the UI uses, keyed by the SF Symbol names
upstream writes (third_party/lucide/icons.map). SwiftPM can't run Qt's rcc, so the icons are compiled in as strings."""
import pathlib, re, sys
root = pathlib.Path(__file__).resolve().parent.parent
pairs = [l.split() for l in (root / "third_party/lucide/icons.map").read_text().splitlines() if l.strip() and not l.startswith("#")]
out = ["// GENERATED by scripts/gen-lucide-icons.py — do not edit. Lucide icons (ISC, third_party/lucide/LICENSE).",
       "#pragma once", "#include <QHash>", "#include <QByteArray>", "#include <QString>", "",
       "/// SVG source for an SF Symbol name upstream uses, drawn from Lucide (the stand-in for SF Symbols); empty if none.",
       "inline QByteArray lucideIconSVG(const QString &symbol) {", "    static const QHash<QString, QByteArray> icons{"]
for sf, name in pairs:
    svg = (root / "third_party/lucide" / (f"{name}.svg" if name.startswith("custom/") else f"icons/{name}.svg")).read_text()
    svg = re.sub(r"<!--.*?-->", "", svg, flags=re.S)
    svg = re.sub(r'\s*class="[^"]*"', "", svg)
    svg = " ".join(svg.split())
    out.append(f'        {{QStringLiteral("{sf}"), QByteArrayLiteral(R"svg({svg})svg")}},')
out += ["    };", "    return icons.value(symbol);", "}", ""]
text = "\n".join(out)


def upstream_symbols():
    """SF Symbol names upstream draws: string literals on lines that name a symbol (systemName:, systemImage:,
    systemSymbolName:, symbol:, badge) and the cases of computed `symbol`/`badge` properties."""
    found = {}
    literal = re.compile(r'"([a-z][a-z0-9]*(?:\.[a-z0-9]+)*)"')
    context = re.compile(r'systemName:|systemImage:|systemSymbolName:|symbol:|\bsymbol\b.*[=?:]|\bbadge\b')
    for path in sorted((root / "Compositor").rglob("*.swift")):
        lines = path.read_text().splitlines()
        block = 0
        for number, line in enumerate(lines, 1):
            if re.search(r"var (symbol|badge): String\??\s*\{", line):
                block = 1 + line.count("{") - line.count("}") - 1
            elif block:
                block += line.count("{") - line.count("}")
            if block or context.search(line):
                for name in literal.findall(line):
                    found.setdefault(name, f"{path.relative_to(root)}:{number}")
            if block <= 0:
                block = 0
    return found


# Literals on symbol lines that are not symbols (identifiers, defaults keys, words in messages).
NOT_SYMBOLS = {"navigator.visible"}

if "--check" in sys.argv:
    problems = []
    if (root / "host/LucideIcons.h").read_text() != text:
        problems.append("host/LucideIcons.h is stale: run scripts/gen-lucide-icons.py")
    mapped = {sf for sf, _ in pairs}
    for name, where in sorted(upstream_symbols().items()):
        if name not in mapped and name not in NOT_SYMBOLS:
            problems.append(f"SF Symbol {name!r} ({where}) has no entry in third_party/lucide/icons.map")
    for problem in problems:
        print(problem)
    print("LUCIDE ICONS OK" if not problems else f"LUCIDE ICONS: {len(problems)} problem(s)")
    sys.exit(1 if problems else 0)
(root / "host/LucideIcons.h").write_text(text)
