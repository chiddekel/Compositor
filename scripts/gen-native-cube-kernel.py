#!/usr/bin/env python3
"""Preserve native fused color-cube interpolation without changing upstream source."""
import argparse
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent


def generate(source):
    replacements = [
        ("c[0] + (c[sx] - c[0]) * fraction[0]", "fmaf(c[sx] - c[0], fraction[0], c[0])"),
        ("c[sy] + (c[sy+sx] - c[sy]) * fraction[0]", "fmaf(c[sy+sx] - c[sy], fraction[0], c[sy])"),
        ("c[sz] + (c[sz+sx] - c[sz]) * fraction[0]", "fmaf(c[sz+sx] - c[sz], fraction[0], c[sz])"),
        ("c[sz+sy] + (c[sz+sy+sx] - c[sz+sy]) * fraction[0]", "fmaf(c[sz+sy+sx] - c[sz+sy], fraction[0], c[sz+sy])"),
        ("x00 + (x10 - x00) * fraction[1]", "fmaf(x10 - x00, fraction[1], x00)"),
        ("x01 + (x11 - x01) * fraction[1]", "fmaf(x11 - x01, fraction[1], x01)"),
        ("y0 + (y1 - y0) * fraction[2]", "fmaf(y1 - y0, fraction[2], y0)"),
    ]
    for original, fused in replacements:
        if source.count(original) != 1:
            raise ValueError(f"Upstream cube expression changed: {original}")
        source = source.replace(original, fused)
    return ("// GENERATED by scripts/gen-native-cube-kernel.py from protected LevelsPixels.c.\n"
            "// Explicit fmaf preserves native arm64 interpolation on baseline Linux CPUs.\n" + source)


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    content = generate((ROOT / "Compositor/Rendering/LevelsPixels.c").read_text())
    output = ROOT / "linux/kernels/LevelsPixelsLinux.c"
    if args.check:
        assert output.read_text() == content, f"Stale native cube kernel: {output}"
    else:
        output.write_text(content)
