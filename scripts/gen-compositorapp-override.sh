#!/usr/bin/env bash
# Regenerates Sources/Overrides/CompositorApp.swift from upstream's Compositor/CompositorApp.swift. The only changes
# include a Color Range menu fallback for older sources that lack it, an editable-kind gate for Edit Adjustment,
# and these mechanical adaptations:
# `#selector(Type.method(_:))` becomes `Selector(("method:"))` (Linux Swift has no Objective-C
# runtime, so `#selector` cannot compile), and `@main` goes (the Linux entry point is CompositorHostBootstrap; the
# shell reads the app's `.commands` to build its menu bar). Run after every upstream merge.
set -euo pipefail
ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
GENERATED=$(mktemp)
trap 'rm -f "$GENERATED"' EXIT
{
    echo "// GENERATED by scripts/gen-compositorapp-override.sh from Compositor/CompositorApp.swift — do not edit."
    echo "// Changes: #selector(T.m(_:)) -> Selector((\"m:\")); @main removed; Edit Adjustment requires settings."
    BODY=$(sed -E -e 's/#selector\(([A-Za-z]+)\.([A-Za-z]+)\(_:\)\)/Selector(("\2:"))/g' -e '/^@main$/d' \
        "$ROOT/Compositor/CompositorApp.swift")
    BODY=$(printf '%s\n' "$BODY" | python3 -c '
import sys
body = sys.stdin.read()
old = ".disabled(!session.canEditLayers || session.activeLayer?.adjustment == nil)"
new = ".disabled(!session.canEditLayers || session.activeLayer?.adjustment?.kind.isEditable != true)"
if body.count(old) != 1:
    raise SystemExit("error: review the Edit Adjustment gate after the upstream change")
body = body.replace(old, new)
# The compat application instance has its own type; native file dialogs are presented through handlers.
body = body.replace("extension NSApplication {", "extension NSApplicationShared {")
body = body.replace("NSApp.keyWindow is NSSavePanel", "NSSavePanel.activePanel != nil")
body = body.replace("keyWindow is NSSavePanel", "NSSavePanel.activePanel != nil")
sys.stdout.write(body)
')
    if ! printf '%s\n' "$BODY" | grep 'beginColorRange' >/dev/null; then
        BODY=$(printf '%s\n' "$BODY" | sed '/\.disabled(!session.canSelectSubject)/a\
                    Button("Color Range…") { session.beginColorRange() }\
                        .disabled(!session.canSelectColorRange)')
    fi
    printf '%s\n' "$BODY"
} > "$GENERATED"
if tail -n +3 "$GENERATED" | grep "#selector" >/dev/null; then
    echo "error: a #selector the script doesn't handle is left in CompositorApp.swift" >&2; exit 1
fi
if [ "${1:-}" = "--check" ]; then
    cmp -s "$GENERATED" "$ROOT/Sources/Overrides/CompositorApp.swift" || {
        echo "CompositorApp override is stale; run scripts/gen-compositorapp-override.sh" >&2; exit 1;
    }
elif ! cmp -s "$GENERATED" "$ROOT/Sources/Overrides/CompositorApp.swift"; then
    cp "$GENERATED" "$ROOT/Sources/Overrides/CompositorApp.swift"
fi
